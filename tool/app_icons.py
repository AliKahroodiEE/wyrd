#!/usr/bin/env python3
"""Cut the Wyrd app icon masters into every size Android, iOS and the web need.

Render the masters first, then run this from the repository root:

    cd app && flutter test --dart-define=SCREENSHOTS=true --update-goldens test/screenshots/app_icon_test.dart
    cd .. && python3 tool/app_icons.py

Inputs (1024 px, from app/build/icons/): icon-square.png (full bleed),
icon-rounded.png (rounded square on transparency), icon-maskable.png (mark in
the central 80 %), icon-foreground.png (mark only, central 66 %) and
icon-background.png (backdrop only). Requires Pillow.

Android also gets ic_stat_wyrd, the white status-bar icon for reminders and
pushes (AndroidManifest.xml and reminder_service.dart name it).
"""

from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
APP = ROOT / "app"
SRC = APP / "build" / "icons"
RES = APP / "android" / "app" / "src" / "main" / "res"
IOS = APP / "ios" / "Runner" / "Assets.xcassets" / "AppIcon.appiconset"

ANDROID_LEGACY = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}
# Adaptive layers are 108 dp; the system crops them to the device's shape.
ANDROID_ADAPTIVE = {"mdpi": 108, "hdpi": 162, "xhdpi": 216, "xxhdpi": 324, "xxxhdpi": 432}
# Status-bar icons are 24 dp, white on transparency, the mark inside 20 dp.
ANDROID_NOTIFICATION = {"mdpi": 24, "hdpi": 36, "xhdpi": 48, "xxhdpi": 72, "xxxhdpi": 96}

ADAPTIVE_XML = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/app_icons.py. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@mipmap/ic_launcher_background" />
    <foreground android:drawable="@mipmap/ic_launcher_foreground" />
    <monochrome android:drawable="@mipmap/ic_launcher_monochrome" />
</adaptive-icon>
"""


def load(name: str) -> Image.Image:
    path = SRC / f"icon-{name}.png"
    if not path.exists():
        raise SystemExit(f"Missing {path}; render the masters first (see the docstring).")
    return Image.open(path).convert("RGBA")


def save(image: Image.Image, size: int, dest: Path, *, opaque: bool = False) -> None:
    dest.parent.mkdir(parents=True, exist_ok=True)
    out = image.resize((size, size), Image.LANCZOS)
    if opaque:
        # iOS and maskable icons must not carry transparency.
        backdrop = Image.new("RGB", out.size, (9, 9, 14))
        backdrop.paste(out, mask=out.getchannel("A"))
        out = backdrop
    out.save(dest, "PNG", optimize=True)
    print(f"{dest.relative_to(ROOT)} ({size}x{size})")


def silhouette(image: Image.Image) -> Image.Image:
    """The mark as solid white: the soft halo and the faint inner rim are
    dropped, since Android draws these layers from their alpha alone."""
    alpha = image.getchannel("A").point(lambda a: 255 if a >= 128 else 0)
    out = Image.new("RGBA", image.size, (255, 255, 255, 0))
    out.putalpha(alpha)
    return out


def status_icon(image: Image.Image) -> Image.Image:
    """[silhouette] cropped to the mark and centred in 20 of 24 units."""
    mark = silhouette(image)
    mark = mark.crop(mark.getchannel("A").getbbox())
    side = round(max(mark.size) * 24 / 20)
    out = Image.new("RGBA", (side, side), (255, 255, 255, 0))
    out.paste(mark, ((side - mark.width) // 2, (side - mark.height) // 2))
    return out


def main() -> None:
    square, rounded, maskable = load("square"), load("rounded"), load("maskable")
    foreground, background = load("foreground"), load("background")

    # Web: favicon, PWA icons, maskable icons and the iOS Home Screen icon.
    save(rounded, 32, APP / "web" / "favicon.png")
    save(rounded, 192, APP / "web" / "icons" / "Icon-192.png")
    save(rounded, 512, APP / "web" / "icons" / "Icon-512.png")
    save(maskable, 192, APP / "web" / "icons" / "Icon-maskable-192.png", opaque=True)
    save(maskable, 512, APP / "web" / "icons" / "Icon-maskable-512.png", opaque=True)
    save(square, 180, APP / "web" / "icons" / "Icon-180.png", opaque=True)

    # Android: legacy launcher icons plus an adaptive icon with a themed
    # (monochrome) layer for Android 13+, and the status-bar icon that
    # reminders and pushes use.
    monochrome = silhouette(foreground)
    notification = status_icon(foreground)
    for density, size in ANDROID_NOTIFICATION.items():
        save(notification, size, RES / f"drawable-{density}" / "ic_stat_wyrd.png")
    for density, size in ANDROID_LEGACY.items():
        save(rounded, size, RES / f"mipmap-{density}" / "ic_launcher.png")
    for density, size in ANDROID_ADAPTIVE.items():
        save(foreground, size, RES / f"mipmap-{density}" / "ic_launcher_foreground.png")
        save(background, size, RES / f"mipmap-{density}" / "ic_launcher_background.png")
        save(monochrome, size, RES / f"mipmap-{density}" / "ic_launcher_monochrome.png")
    adaptive = RES / "mipmap-anydpi-v26" / "ic_launcher.xml"
    adaptive.parent.mkdir(parents=True, exist_ok=True)
    adaptive.write_text(ADAPTIVE_XML)
    print(adaptive.relative_to(ROOT))

    # iOS: every file the asset catalog lists, at the size in its name.
    for existing in sorted(IOS.glob("Icon-App-*.png")):
        points, scale = existing.stem.removeprefix("Icon-App-").split("@")
        size = round(float(points.split("x")[0]) * int(scale.removesuffix("x")))
        save(square, size, existing, opaque=True)


if __name__ == "__main__":
    main()
